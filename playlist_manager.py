"""
playlist_manager.py — YouTube kanalında tematik playlist yönetimi.

Video yüklendikten sonra ilgili playlist'e otomatik ekler.
Playlist yoksa oluşturur.

Playlist'ler script'teki tag'lere göre belirlenir:
  - "rome", "greek", "persian" → "Ancient World"
  - "ww2", "world war", "nazi" → "World War II"
  - "napoleon", "french" → "European History"
  - vs. → "What If History" (varsayılan)

Gereksinim: YOUTUBE_TOKEN_JSON
"""

import json
import os
import re
import tempfile

try:
    from googleapiclient.discovery import build
    from google.oauth2.credentials import Credentials
    from google.auth.transport.requests import Request
    YOUTUBE_AVAILABLE = True
except ImportError:
    YOUTUBE_AVAILABLE = False


SCOPES = ["https://www.googleapis.com/auth/youtube"]

PLAYLIST_STATE_PATH = "playlist_ids.json"

# Konu → Playlist eşleşme kuralları (öncelik sırasıyla)
